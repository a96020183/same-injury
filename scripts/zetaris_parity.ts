// What the product loses without Zetaris: the same statements, as the agents' role and as the administrator, on live
// Zetaris and on the bundled single-process SQLite emulator. Writes docs/zetaris_vs_emulator.md.
// Needs the local Zetaris (scripts/setup_zetaris.py + setup_governance.py). Usage: node --import tsx scripts/zetaris_parity.ts
process.env.SAMPLE_MODE = "false";
import { writeFileSync } from "node:fs";
const { SqlTool } = await import("../app/zetaris.ts");

const live = new SqlTool({ mode: "live" });
const emu = new SqlTool({ mode: "sample", dir: "sample/seed1003" });
(emu as unknown as { cassette: Map<string, unknown> }).cassette.clear(); // the emulator itself, not the recording

const SIR = "osha_public.severe_injury_reports";
const checks: { what: string; sql: string; admin?: boolean; why: string }[] = [
  { what: "Agent role reads an employer column", sql: `SELECT ID, Employer, Address1 FROM ${SIR} WHERE ID = 'SIR-SYN002'`,
    why: "Column policy, enforced by the server for the role. The emulator can only copy the mask into its own loader." },
  { what: "Reviewer (administrator) reads the same row", sql: `SELECT ID, Employer, Address1 FROM ${SIR} WHERE ID = 'SIR-SYN002'`, admin: true,
    why: "One copy of the data, two identities. The emulator has no identities, so it cannot give the reviewer the names." },
  { what: "Agent role tries to widen its own access", sql: `GRANT SELECT ON LIGHTNING DATABASE TABLE ${SIR} TO ROLE 'L1_AGENT'`,
    why: "Only an administrator can GRANT. The emulator has no roles." },
  { what: "Agent role tries to compile the unified model itself", sql: "COMPILE USL injury_records_probe DEPLOY NAMESPACE lightning.metastore.l1 DDL\nCREATE TABLE t (a varchar(4))",
    why: "COMPILE USL is the step a person approves. Zetaris enforces it; the emulator would accept it." },
  { what: "Agent role reads a source it was never assigned", sql: "SELECT count(*) AS n FROM exam2003_my.inc_rpt",
    why: "Another company's system on the same gateway (loaded by scripts/load_company_zetaris.py). The role does not see it." },
];

const fmt = (r: Awaited<ReturnType<typeof live.run>>) => r.ok
  ? (r.result.data.length ? JSON.stringify(r.result.data[0]).slice(0, 90) : "accepted (no rows)")
  : "refused: " + String(r.receipt.error).replace(/\s+/g, " ").replace(/^Zetaris HTTP \d+: /, "").slice(0, 110);
const rows: string[] = [];
for (const c of checks) {
  const a = await live.run(c.sql, c.what, "parity", { admin: c.admin });
  const b = await emu.run(c.sql, c.what, "parity", { admin: c.admin });
  rows.push(`| ${c.what} (${c.admin ? "administrator" : "agent role"}) | ${fmt(a).replace(/\|/g, "/")} | ${fmt(b).replace(/\|/g, "/")} | ${c.why} |`);
  console.log(c.what, "\n   live:", fmt(a), "\n   emulator:", fmt(b));
}
const md = `# What Zetaris does that a single-process SQLite copy cannot

Generated by \`scripts/zetaris_parity.ts\` on ${new Date().toISOString().slice(0, 10)} against the local Zetaris 2.4.3.1, and the bundled emulator
(\`app/emulator.ts\`, the SAMPLE_MODE fallback) on the same de-identified data.

| Statement | Live Zetaris | Emulator (SQLite) | Why it matters |
|---|---|---|---|
${rows.join("\n")}

## What would be lost

- **The data would have to move.** The emulator works because every table was first exported to CSV and loaded into one process.
  A plant's EHS database, a MySQL incident system, a CSV share and the transcribed paper log stay where they are behind
  Zetaris; the candidate map is one federated query across them, OSHA's file and DOL (filters pushed down to each engine:
  \`docs/explain_candidate_map.txt\`).
- **Identity would be a convention, not a control.** Masks in the emulator are a copy of the policy applied at load time:
  anyone with the CSVs reads the names. In Zetaris the agents' key cannot read them, cannot grant itself more, cannot compile
  the unified model and cannot see another company's sources.
- **The person-approval step would have no teeth.** COMPILE USL runs only with the administrator key after a person approves
  the draft; the emulator would compile whatever the agent sent.
- **The reviewer view would not exist.** The review queue shows the same SQL answered for the agent role and for the
  administrator, side by side. The emulator has one answer.

In SAMPLE_MODE the GRANT statements are answered by the recording of the live run. If a statement was never recorded,
the emulator answers it and says "emulator: not enforced", and the receipt shows \`backend: emulator\`.
`;
writeFileSync("docs/zetaris_vs_emulator.md", md);
console.log("wrote docs/zetaris_vs_emulator.md");
